#!/usr/bin/env bash
# setup.sh — fetch the official GhidraMCP stdio bridge and generate DSH wiring.
#
#   bash scripts/setup.sh                 # build .venv + bridge, write ghidra-mcp.patch.yml
#   bash scripts/setup.sh --profile desktop
#                                         # also append the MCP row to that profile's
#                                         # cordis.patch.yml (skips if already present)
#
# Idempotent: re-running refreshes the bridge script and rewrites the patch.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENV="$ROOT/.venv"
BRIDGE="$ROOT/bridge_mcp_ghidra.py"
PATCH="$ROOT/ghidra-mcp.patch.yml"
BRIDGE_URL="https://raw.githubusercontent.com/LaurieWired/GhidraMCP/main/bridge_mcp_ghidra.py"
PROFILE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile) PROFILE="${2:-}"; shift 2 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

echo "== python venv"
[[ -x "$VENV/bin/python" ]] || python3 -m venv "$VENV"
"$VENV/bin/pip" install --quiet --upgrade pip >/dev/null
"$VENV/bin/pip" install --quiet mcp

echo "== fetch bridge_mcp_ghidra.py"
curl -fsSL -o "$BRIDGE" "$BRIDGE_URL"
chmod +x "$BRIDGE"

echo "== write ghidra-mcp.patch.yml"
cat > "$PATCH" <<YAML
# GhidraMCP over stdio, generated by ghidra-bridge/scripts/setup.sh
# Prerequisite: Ghidra is running with the GhidraMCP extension enabled on
# http://127.0.0.1:8080/ . Tools appear as mcp__ghidra__*.
- insert:
    - id: mcp-ghidra
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: ghidra
        transport: stdio
        command: $VENV/bin/python
        args:
          - $BRIDGE
          - '--ghidra-server'
          - 'http://127.0.0.1:8080/'
        toolCallTimeoutMs: 120000
        failOnStartupError: false
        reconnect:
          enabled: true
          maxAttempts: 5
YAML

# A portable .mcp.json for clients that still read that convention.
python3 - "$ROOT/.mcp.json" "$VENV/bin/python" "$BRIDGE" <<'PY'
import json, sys
path, py, bridge = sys.argv[1], sys.argv[2], sys.argv[3]
config = {"mcpServers": {"ghidra": {"command": py, "args": [bridge, "--ghidra-server", "http://127.0.0.1:8080/"]}}}
with open(path, "w", encoding="utf-8") as handle:
    json.dump(config, handle, indent=2, ensure_ascii=False)
    handle.write("\n")
PY

if [[ -n "$PROFILE" ]]; then
  PROFILE_PATCH="$HOME/.dsh/profiles/$PROFILE/cordis.patch.yml"
  if [[ ! -f "$PROFILE_PATCH" ]]; then
    echo "profile patch not found: $PROFILE_PATCH" >&2
    exit 1
  fi
  if grep -q 'mcp-ghidra' "$PROFILE_PATCH"; then
    echo "== profile $PROFILE already wires mcp-ghidra; left unchanged"
  else
    echo "== append mcp-ghidra row to $PROFILE_PATCH"
    cp "$PROFILE_PATCH" "$PROFILE_PATCH.bak-$(date +%Y%m%d-%H%M%S)"
    printf '\n# ghidra-bridge\n' >> "$PROFILE_PATCH"
    # Append only the insert list body from the generated patch.
    sed -n '/^- insert:/,$p' "$PATCH" >> "$PROFILE_PATCH"
  fi
fi

echo "done."
echo "1) 启动 Ghidra，打开 CodeBrowser，File → Configure → 勾选 GhidraMCPPlugin"
echo "2) 确认桥接口：curl -s http://127.0.0.1:8080/methods?limit=5"
echo "3) 若未写 profile：把 ghidra-mcp.patch.yml 合并进 profile 的 cordis.patch.yml，或重启 DSH"
echo "4) 会话里用 mcp__ghidra__* 工具；冒烟：让模型列出当前样本前 5 个函数"
